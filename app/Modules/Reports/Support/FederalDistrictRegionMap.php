    /**
     * Определить короткое название ФО по названию региона.
     *
     * @param string|null $region Название региона (как в БД)
     * @return string|null Ключ ФО (cfo, szfo, …) или null если не определено
     */
    public function resolveShortName(?string $region): ?string
    {
        $normalized = $this->normalizeRegion($region);
        if ($normalized === '') {
            return null;
        }
        return self::REGION_TO_DISTRICT[$normalized] ?? null;
    }

    /**
     * Нормализовать название региона для сопоставления.
     *
     * - trim
     * - mb_strtolower
     * - замена Ё/ё → Е/е
     * - замена неразрывных пробелов
     * - схлопывание повторных пробелов
     *
     * @param string|null $region
     * @return string
     */
    public function normalizeRegion(?string $region): string
    {
        if ($region === null) {
            return '';
        }
        $s = trim($region);
        if ($s === '') {
            return '';
        }
        $s = mb_strtolower($s, 'UTF-8');
        // Замена Ё/ё
        $s = str_replace(['ё'], ['е'], $s);
        // Неразрывные пробелы (разные варианты)
        $s = str_replace(["\xc2\xa0", "\xa0", ' '], ' ', $s);
        // Схлопнуть повторные пробелы
        $s = preg_replace('/\s+/u', ' ', $s);
        return trim($s);
    }

    /**
     * Порядок ключей ФО для сортировки строк.
